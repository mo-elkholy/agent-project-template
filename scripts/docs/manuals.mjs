// Optional module: generate one user manual per language from shared Help
// content, so in-app Help and the written manuals cannot drift apart.
// Usage: node scripts/docs/manuals.mjs [--check] [--source docs/help-content.json]
// --check exits 1 when a generated manual is stale. Never hand-edit the output.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

function text(topic, field, code) {
  const value = topic[field]?.[code];
  if (value === undefined || value === "" || (Array.isArray(value) && !value.length))
    throw new Error(`missing ${code} translation for ${topic.id}.${field}`);
  return value;
}

export function renderManuals(data) {
  const ids = new Set(data.topics.map((t) => t.id));
  for (const topic of data.topics)
    for (const id of topic.related ?? [])
      if (!ids.has(id)) throw new Error(`${topic.id}: unknown related topic ${id}`);
  const output = {};
  for (const lang of data.languages) {
    const { code } = lang;
    const lines = [
      "---",
      `type: "User Manual"`,
      `title: ${JSON.stringify(lang.title)}`,
      `description: ${JSON.stringify(lang.description)}`,
      `status: "stable"`,
      `owner: ${JSON.stringify(data.owner ?? "Project")}`,
      `generated: {"by": "process:manuals", "at": "${data.updated}T00:00:00Z"}`,
      `tracks: ["docs/help-content.json", "scripts/docs/manuals.mjs"]`,
      `sources: [{"resource": "help-content.json"}]`,
      `dir: ${JSON.stringify(lang.dir ?? "ltr")}`,
      "---",
      `# ${lang.title}`,
      "",
      "Generated from `docs/help-content.json` by `node scripts/docs/manuals.mjs`. Do not edit this file directly.",
      "",
    ];
    for (const topic of data.topics) lines.push(`- [${text(topic, "title", code)}](#${topic.id})`);
    for (const topic of data.topics) {
      lines.push("", `<a id="${topic.id}"></a>`, `## ${text(topic, "title", code)}`, "", text(topic, "hint", code), "");
      text(topic, "steps", code).forEach((step, i) => lines.push(`${i + 1}. ${step}`));
      if (topic.related?.length) {
        const label = lang.relatedLabel ?? "Related";
        const links = topic.related.map((id) => {
          const target = data.topics.find((t) => t.id === id);
          return `[${text(target, "title", code)}](#${id})`;
        });
        lines.push("", `${label}: ${links.join(" · ")}`);
      }
    }
    output[code] = lines.join("\n") + "\n";
  }
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  const args = process.argv.slice(2);
  const sourceIndex = args.indexOf("--source");
  const source = path.join(root, sourceIndex > -1 ? args[sourceIndex + 1] : "docs/help-content.json");
  try {
    const manuals = renderManuals(JSON.parse(fs.readFileSync(source, "utf8")));
    for (const [code, body] of Object.entries(manuals)) {
      const file = path.join(root, `docs/manual-${code}.md`);
      if (args.includes("--check")) {
        const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
        if (current !== body) {
          console.error(`Stale docs/manual-${code}.md: run node scripts/docs/manuals.mjs`);
          process.exitCode = 1;
        }
      } else fs.writeFileSync(file, body);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

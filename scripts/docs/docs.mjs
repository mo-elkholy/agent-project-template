import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const hash = (value) => crypto.createHash("sha256").update(value).digest("hex");
const reserved = new Set(["index.md", "log.md"]);
const defaults = {
  title: "Project documentation",
  trackRoots: ["src", "scripts", "tests", "docs", ".agents", "AGENTS.md", "README.md", "package.json"],
  linkCheckedFiles: ["AGENTS.md", "README.md"],
  requiredKeys: ["type", "title", "description", "owner"],
  statuses: ["draft", "stable", "deprecated"],
};
let config = defaults;
function loadConfig(root) {
  const file = path.join(root, "docs/docs.config.json");
  const custom = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : {};
  return { ...defaults, ...custom };
}
const slash = (value) => value.split(path.sep).join("/");
const stamp = (value) =>
  typeof value === "string" &&
  /^\d{4}-\d{2}-\d{2}T.+(?:Z|[+-]\d{2}:\d{2})$/.test(value) &&
  Number.isFinite(Date.parse(value));

function contained(root, relative) {
  const target = path.resolve(root, relative);
  const assertInside = (candidate) => {
    const rel = path.relative(root, candidate);
    if (rel === ".." || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel))
      throw new Error(`Path escapes repository: ${relative}`);
  };
  assertInside(target);
  if (fs.existsSync(target)) assertInside(fs.realpathSync(target));
  return target;
}
function files(root, directory) {
  const target = contained(root, directory);
  if (!fs.existsSync(target)) return [];
  return fs
    .readdirSync(target, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, "en"))
    .flatMap((entry) => {
      const rel = slash(path.join(directory, entry.name));
      if (entry.isSymbolicLink())
        throw new Error(
          `Symlinks are not supported as documentation inputs: ${rel}`,
        );
      return entry.isDirectory() ? files(root, rel) : [rel];
    });
}
function readDoc(root, relative) {
  const text = fs.readFileSync(contained(root, relative), "utf8");
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
  if (!match) throw new Error(`${relative}: missing YAML frontmatter`);
  const meta = yaml.load(match[1], { schema: yaml.JSON_SCHEMA });
  if (!meta || typeof meta !== "object" || Array.isArray(meta))
    throw new Error(`${relative}: invalid frontmatter mapping`);
  return { relative, text, meta, body: text.slice(match[0].length) };
}
function concepts(root) {
  return files(root, "docs")
    .filter(
      (file) => file.endsWith(".md") && !reserved.has(path.basename(file)),
    )
    .map((file) => readDoc(root, file));
}
function fingerprint(root, relative) {
  const top = relative.split("/")[0];
  if (
    !relative ||
    relative.startsWith("/") ||
    relative.includes("..") ||
    !config.trackRoots.includes(top)
  )
    throw new Error(`Unsupported tracked path: ${relative}`);
  const target = contained(root, relative);
  if (!fs.existsSync(target)) return null;
  const names = fs.statSync(target).isDirectory()
    ? files(root, relative)
    : [relative];
  if (
    names.some(
      (name) =>
        name === "docs/.sync-state.json" ||
        reserved.has(path.basename(name)) ||
        path.basename(name).startsWith("."),
    )
  )
    throw new Error(
      `Track explicit documentation files, not indexes/state: ${relative}`,
    );
  return hash(
    JSON.stringify(
      names.map((name) => [name, hash(fs.readFileSync(contained(root, name)))]),
    ),
  );
}
function snapshot(root, doc) {
  if (
    !Array.isArray(doc.meta.tracks) ||
    doc.meta.tracks.some((p) => typeof p !== "string")
  )
    throw new Error(`${doc.relative}: tracks must be an array of paths`);
  return {
    document: hash(doc.text),
    inputs: Object.fromEntries(
      doc.meta.tracks.map((p) => [p, fingerprint(root, p)]),
    ),
  };
}
function heading(name) {
  return name.charAt(0).toUpperCase() + name.slice(1).replace(/-/g, " ");
}
function indexes(docs) {
  const dirs = new Set(["docs"]);
  for (const doc of docs) {
    let dir = path.posix.dirname(doc.relative);
    while (dir !== ".") {
      dirs.add(dir);
      if (dir === "docs") break;
      dir = path.posix.dirname(dir);
    }
  }
  const output = {};
  for (const dir of [...dirs].sort()) {
    let text =
      dir === "docs"
        ? `---\nokf_version: "0.2"\n---\n# ${config.title}\n\nGenerated by \`npm run docs:sync\`. Start with [the documentation specification](SPEC.md); use [the update log](log.md) for recent changes. Proposals are not shipped features.\n\n`
        : `# ${heading(path.posix.basename(dir))}\n\n`;
    text += "## Documents\n\n";
    for (const doc of docs
      .filter((d) => path.posix.dirname(d.relative) === dir)
      .sort((a, b) => a.relative.localeCompare(b.relative, "en"))) {
      text += `- [${doc.meta.title}](${path.posix.basename(doc.relative)}) - ${doc.meta.description} (${doc.meta.status})\n`;
    }
    const children = [...dirs]
      .filter((d) => d !== dir && path.posix.dirname(d) === dir)
      .sort();
    if (children.length)
      text +=
        "\n## Subdirectories\n\n" +
        children
          .map(
            (d) =>
              `- [${path.posix.basename(d)}](${path.posix.basename(d)}/index.md) - ${config.directories?.[path.posix.basename(d)] ?? "Supporting documents."}\n`,
          )
          .join("");
    output[`${dir}/index.md`] = text;
  }
  return output;
}
function localLink(root, from, value, virtual = new Set()) {
  if (/^[a-z][a-z\d+.-]*:/i.test(value) || value.startsWith("#")) return;
  let link = decodeURIComponent(value.replace(/^<|>$/g, "").split(/[?#]/)[0]);
  if (!link) return;
  const target = link.startsWith("/")
    ? `docs/${link.slice(1)}`
    : path.join(path.dirname(from), link);
  if (
    !virtual.has(slash(path.relative(root, contained(root, target)))) &&
    !fs.existsSync(contained(root, target))
  )
    throw new Error(`${from}: broken local link ${value}`);
}
function bodyLinks(root, from, text, virtual, attempt) {
  const body = text
    .replace(/^(```|~~~)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, "")
    .replace(/`[^`]*`/g, "");
  for (const match of body.matchAll(
    /\[[^\]\n]*\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g,
  ))
    attempt(() => localLink(root, from, match[1], virtual));
  for (const match of body.matchAll(/^ {0,3}\[[^\]\n]+\]:\s*(<[^>]+>|\S+)/gm)) {
    if (!match[0].trimStart().startsWith("[^"))
      attempt(() => localLink(root, from, match[1], virtual));
  }
}
function validate(root, docs, virtual) {
  const errors = [],
    warnings = [];
  const attempt = (fn) => {
    try {
      fn();
    } catch (e) {
      errors.push(e.message);
    }
  };
  for (const doc of docs)
    attempt(() => {
      const m = doc.meta;
      for (const key of config.requiredKeys)
        if (typeof m[key] !== "string" || !m[key].trim())
          throw new Error(`${doc.relative}: missing ${key}`);
      if (!config.statuses.includes(m.status))
        throw new Error(`${doc.relative}: invalid lifecycle status`);
      if (typeof m.generated?.by !== "string" || !stamp(m.generated.at))
        throw new Error(`${doc.relative}: invalid generated actor/timestamp`);
      if (!Array.isArray(m.sources))
        throw new Error(`${doc.relative}: sources must be an array`);
      for (const src of m.sources) {
        if (typeof src?.resource !== "string" || !src.resource.trim())
          throw new Error(`${doc.relative}: source requires resource`);
        // Scope descriptors are legitimate OKF sources; path-looking values get checked.
        if (
          src.resource.startsWith("/") ||
          src.resource.startsWith(".") ||
          /\.(md|ts|tsx|mjs|json|txt)$/.test(src.resource)
        )
          localLink(root, doc.relative, src.resource, virtual);
      }
      if (m.verified)
        for (const event of Array.isArray(m.verified)
          ? m.verified
          : [m.verified])
          if (typeof event?.by !== "string" || !stamp(event.at))
            throw new Error(`${doc.relative}: invalid verified event`);
      if (m.stale_after) {
        if (!stamp(m.stale_after))
          throw new Error(`${doc.relative}: invalid stale_after`);
        if (Date.now() >= Date.parse(m.stale_after))
          warnings.push(`${doc.relative}: freshness review is due`);
      }
      const snap = snapshot(root, doc);
      for (const [input, digest] of Object.entries(snap.inputs))
        if (digest === null)
          errors.push(`${doc.relative}: missing tracked input ${input}`);
      if (m.external_snapshot) {
        if (
          !/^[a-f\d]{64}$/.test(m.upstream_sha256 ?? "") ||
          hash(doc.body) !== m.upstream_sha256
        )
          throw new Error(`${doc.relative}: upstream snapshot hash mismatch`);
      } else {
        bodyLinks(root, doc.relative, doc.body, virtual, attempt);
      }
    });
  for (const file of [
    ...files(root, "docs").filter((f) => path.basename(f) === "log.md"),
    ...config.linkCheckedFiles,
  ]) {
    if (fs.existsSync(contained(root, file)))
      bodyLinks(
        root,
        file,
        fs.readFileSync(contained(root, file), "utf8"),
        virtual,
        attempt,
      );
  }
  return { errors, warnings };
}
const statePath = (root) => path.join(root, "docs/.sync-state.json");
function loadState(root) {
  return fs.existsSync(statePath(root))
    ? JSON.parse(fs.readFileSync(statePath(root), "utf8"))
    : { version: 1, documents: {} };
}
export function runDocs(root, command = "check", args = []) {
  root = fs.realpathSync(root);
  config = loadConfig(root);
  const docs = concepts(root),
    expected = indexes(docs),
    result = validate(root, docs, new Set(Object.keys(expected)));
  if (result.errors.length) return result;
  if (command === "sync") {
    for (const [file, text] of Object.entries(expected))
      fs.writeFileSync(contained(root, file), text);
    return {
      ...result,
      message: `Generated ${Object.keys(expected).length} documentation indexes; review receipts unchanged.`,
    };
  }
  const state = loadState(root);
  if (
    state.version !== 1 ||
    !state.documents ||
    typeof state.documents !== "object"
  )
    throw new Error("Unsupported documentation sync state");
  if (command === "ack") {
    const names = [];
    let by = "",
      note = "";
    for (let i = 0; i < args.length; i++) {
      if (args[i] === "--by") by = args[++i] ?? "";
      else if (args[i] === "--note") note = args[++i] ?? "";
      else if (args[i].startsWith("--"))
        throw new Error(`Unknown option: ${args[i]}`);
      else names.push(slash(args[i]).replace(/^\.\//, ""));
    }
    if (!names.length || !by.trim() || !note.trim())
      throw new Error(
        "Name reviewed documents and supply --by and --note; no blanket acknowledgment.",
      );
    // Validate the whole request before writing any receipts.
    const selected = names.map((name) => {
      const doc = docs.find((d) => d.relative === name);
      if (!doc) throw new Error(`Unknown concept: ${name}`);
      return doc;
    });
    for (const doc of selected)
      state.documents[doc.relative] = {
        ...snapshot(root, doc),
        reviewed_at: new Date().toISOString(),
        by,
        note,
      };
    for (const key of Object.keys(state.documents))
      if (!docs.some((d) => d.relative === key)) delete state.documents[key];
    const temp = statePath(root) + ".tmp";
    fs.writeFileSync(temp, JSON.stringify(state, null, 2) + "\n");
    fs.renameSync(temp, statePath(root));
    return {
      ...result,
      message: `Recorded explicit source-change review for ${selected.length} documents; no OKF verification added.`,
    };
  }
  if (command !== "check") throw new Error(`Unknown docs command: ${command}`);
  for (const [file, text] of Object.entries(expected))
    if (
      !fs.existsSync(contained(root, file)) ||
      fs.readFileSync(contained(root, file), "utf8") !== text
    )
      result.errors.push(`${file}: index is stale; run npm run docs:sync`);
  for (const doc of docs) {
    const current = snapshot(root, doc),
      prior = state.documents[doc.relative];
    if (!prior)
      result.errors.push(`${doc.relative}: no source-change review receipt`);
    else if (
      prior.document !== current.document ||
      JSON.stringify(prior.inputs) !== JSON.stringify(current.inputs)
    )
      result.errors.push(
        `${doc.relative}: document or tracked inputs changed; review prose, then acknowledge explicitly`,
      );
  }
  for (const key of Object.keys(state.documents))
    if (!docs.some((d) => d.relative === key))
      result.errors.push(
        `${key}: obsolete receipt; refresh indexes and acknowledge reviewed documents`,
      );
  for (const file of files(root, "docs").filter(
    (f) => path.basename(f) === "index.md",
  )) {
    if (!Object.hasOwn(expected, file))
      result.errors.push(
        `${file}: orphan index; remove it or add concepts for this directory`,
      );
  }
  for (const file of files(root, "docs").filter(
    (f) => path.basename(f) === "log.md",
  )) {
    const body = fs.readFileSync(contained(root, file), "utf8");
    if (body.startsWith("---"))
      result.errors.push(`${file}: logs have no frontmatter`);
    for (const line of body
      .split("\n")
      .filter((line) => line.startsWith("## ")))
      if (!/^## \d{4}-\d{2}-\d{2}$/.test(line))
        result.errors.push(`${file}: invalid log date heading`);
  }
  return {
    ...result,
    message: `Checked ${docs.length} OKF concepts and ${Object.keys(expected).length} generated indexes.`,
  };
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const result = runDocs(
      path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../.."),
      process.argv[2] ?? "check",
      process.argv.slice(3),
    );
    for (const warning of result.warnings) console.warn(`WARNING ${warning}`);
    for (const error of result.errors) console.error(`ERROR ${error}`);
    if (result.message) console.log(result.message);
    process.exitCode = result.errors.length ? 1 : 0;
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
